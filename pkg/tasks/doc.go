// Package tasks предоставляет PostgreSQL-backed runner для отложенных и фоновых задач.
//
// Конкретную задачу идентифицирует пара Source и SourceID. Повторный Enqueue той же
// пары не создаёт дубликат. Опциональный SerialKey объединяет разные задачи в FIFO-
// очередь: одновременно выполняется не более одной задачи с одинаковым непустым
// ключом, включая выполнение на разных репликах приложения.
//
// Runner обеспечивает at-least-once выполнение. Handler должен быть идемпотентным,
// потому что после истечения lease задача может быть запущена повторно. Attempt
// используется как fencing token и не позволяет завершившейся поздно попытке изменить
// состояние задачи, уже перехваченной другой репликой.
